// Writes lib/apiv1/openapi-routes.ts: a static import list of every app/api/v1/**/route.ts,
// with its public path derived from the file location. `buildOpenApi()` loads each module and
// reads the operations `withApi` stamped on its exports. tests/apiv1-openapi-index.test.ts
// fails when this file is stale — run `npm run gen:v1-index` after adding or moving a route.
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const base = path.join(root, "app", "api", "v1");
const SKIP = ["app/api/v1/openapi.json/route.ts"];

function routeFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    if (d.isDirectory()) return routeFiles(p);
    return d.name === "route.ts" ? [path.relative(root, p).split(path.sep).join("/")] : [];
  });
}

const files = routeFiles(base)
  .filter((f) => !SKIP.includes(f))
  .sort();

const entries = files.map((file) => {
  const dir = file.replace(/^app/, "").replace(/\/route\.ts$/, "");
  const routePath = dir.replace(/\[([^\]]+)\]/g, "{$1}");
  const mod = "@/" + file.replace(/\.ts$/, "");
  return `  { path: ${JSON.stringify(routePath)}, file: ${JSON.stringify(file)}, load: () => import(${JSON.stringify(mod)}) },`;
});

const out = `// GENERATED by scripts/gen-v1-index.mjs — do not edit. Run \`npm run gen:v1-index\`.
export type V1Route = { path: string; file: string; load: () => Promise<Record<string, unknown>> };

export const V1_ROUTES: V1Route[] = [
${entries.join("\n")}
];

/** The route files this index was generated from, for the currency test. */
export function expectedRouteFiles(): string[] {
  return V1_ROUTES.map((r) => r.file);
}
`;

const target = path.join(root, "lib", "apiv1", "openapi-routes.ts");
writeFileSync(target, out, "utf8");
console.log(`wrote ${path.relative(root, target)} (${files.length} routes)`);
